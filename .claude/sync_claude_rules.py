"""
Mirror glob-scoped Cursor rules into Claude Code path-scoped rules.

``.cursor/rules/*.mdc`` is canonical. Claude Code does not read Cursor frontmatter, so each rule
with ``globs`` and ``alwaysApply: false`` is copied to ``.claude/rules/<name>.md`` with a
``paths:`` list; Claude then loads it when it reads or edits a matching file. Always-applied
rules stay as ``@`` imports in ``CLAUDE.md``; this script checks that none is missing.

Usage (from the monorepo root):
    python .claude/sync_claude_rules.py          # write .claude/rules/
    python .claude/sync_claude_rules.py --check  # exit 1 if out of date or CLAUDE.md lacks an import
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

REPO_ROOT: Path = Path(__file__).resolve().parent.parent
CURSOR_RULES: Path = REPO_ROOT / ".cursor" / "rules"
CLAUDE_RULES: Path = REPO_ROOT / ".claude" / "rules"
CLAUDE_MD: Path = REPO_ROOT / "CLAUDE.md"
GENERATED_MARKER: str = "<!-- Generated by .claude/sync_claude_rules.py"

_LINK_RE: re.Pattern[str] = re.compile(r"\]\((?!https?:|#|/)([^)]+)\)")


@dataclass
class CursorRule:
    name: str
    always_apply: bool
    globs: list[str]
    body: str


def split_globs(value: str) -> list[str]:
    """Split a Cursor ``globs`` value on commas that are not inside ``{...}``."""
    parts: list[str] = []
    depth = 0
    current = ""
    for ch in value:
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(current)
            current = ""
        else:
            current += ch
    parts.append(current)
    return [p.strip().strip("'\"") for p in parts if p.strip().strip("'\"")]


def parse_rule(path: Path) -> CursorRule:
    """Parse a ``.mdc`` file's frontmatter by hand (Cursor globs are often not valid YAML)."""
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---"):
        return CursorRule(path.stem, False, [], text)
    _, front, body = text.split("---", 2)
    lines = front.strip("\r\n").splitlines()
    fields: dict[str, str] = {}
    i = 0
    while i < len(lines):
        key, sep, value = lines[i].partition(":")
        i += 1
        if not sep:
            continue
        value = value.strip()
        if value in (">", "|", ">-", "|-"):
            block: list[str] = []
            while i < len(lines) and (lines[i].startswith((" ", "\t")) or not lines[i].strip()):
                block.append(lines[i].strip())
                i += 1
            value = "".join(block) if value.startswith(">") else ",".join(block)
        fields[key.strip()] = value
    always = fields.get("alwaysApply", "false").lower() == "true"
    globs = split_globs(fields.get("globs", ""))
    return CursorRule(path.stem, always, globs, body.lstrip("\r\n"))


def rebase_links(body: str) -> str:
    """Rewrite relative Markdown links from ``.cursor/rules/`` to ``.claude/rules/``."""

    def fix(match: re.Match[str]) -> str:
        target = match.group(1)
        if target.startswith("../../"):
            return match.group(0)
        if target.startswith("../"):
            return f"](../../.cursor/{target[3:]})"
        return f"](../../.cursor/rules/{target})"

    return _LINK_RE.sub(fix, body)


def render(rule: CursorRule) -> str:
    """Return the Claude rule file content for a glob-scoped Cursor rule."""
    paths = "\n".join(f'  - "{g}"' for g in rule.globs)
    return (
        f"---\npaths:\n{paths}\n---\n\n"
        f"{GENERATED_MARKER} from .cursor/rules/{rule.name}.mdc; edit that file, then rerun. -->\n\n"
        f"{rebase_links(rule.body).rstrip()}\n"
    )


def main() -> int:
    """Write or check ``.claude/rules/`` and report always-applied rules missing from CLAUDE.md."""
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="report drift without writing")
    args = parser.parse_args()

    rules = [parse_rule(p) for p in sorted(CURSOR_RULES.glob("*.mdc"))]
    expected = {f"{r.name}.md": render(r) for r in rules if not r.always_apply and r.globs}
    problems: list[str] = []

    claude_md = CLAUDE_MD.read_text(encoding="utf-8")
    for r in rules:
        if r.always_apply and f"@.cursor/rules/{r.name}.mdc" not in claude_md:
            problems.append(f"CLAUDE.md does not import always-applied rule {r.name}.mdc")
        if not r.always_apply and not r.globs:
            problems.append(f"{r.name}.mdc has neither alwaysApply nor globs; Claude will never load it")

    existing = {p.name: p for p in CLAUDE_RULES.glob("*.md")} if CLAUDE_RULES.exists() else {}
    for name, path in existing.items():
        if name not in expected and path.read_text(encoding="utf-8").find(GENERATED_MARKER) >= 0:
            problems.append(f"stale generated rule .claude/rules/{name}")
            if not args.check:
                path.unlink()
    for name, content in expected.items():
        path = CLAUDE_RULES / name
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        if args.check:
            problems.append(f".claude/rules/{name} is out of date")
        else:
            CLAUDE_RULES.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
            print(f"wrote .claude/rules/{name}")

    for p in problems:
        print(p, file=sys.stderr)
    return 1 if args.check and problems else 0


if __name__ == "__main__":
    sys.exit(main())
